#!/usr/bin/env python3
"""Rebuild self-hosted Maple Mono v7.9 with fonttools[woff]==4.61.1.

Usage: python scripts/build-maple-fonts.py /path/to/MapleMonoNormalNL-NF-CN.zip
Verify the archive against its official .sha256 before running.
The original font family, all encoded characters and OpenType layout are retained.
"""
from pathlib import Path
from tempfile import TemporaryDirectory
import hashlib
import sys
import zipfile
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
DEST = ROOT / "public/fonts/maple-mono"
FAMILY = "Maple Mono Normal NL NF CN"


def unicode_ranges(points):
    ranges = []
    start = end = points[0]
    for point in points[1:]:
        if point == end + 1:
            end = point
        else:
            ranges.append(f"U+{start:X}" + (f"-{end:X}" if start != end else ""))
            start = end = point
    ranges.append(f"U+{start:X}" + (f"-{end:X}" if start != end else ""))
    return ",".join(ranges)


def build(archive):
    expected = "af8082c484cb1103da6c2efa4b76f403fe342f9a3ac81ff665b8c6c66c2f8863"
    with open(archive, "rb") as stream:
        if hashlib.file_digest(stream, "sha256").hexdigest() != expected:
            raise SystemExit("Archive SHA-256 does not match the official Maple Mono v7.9 release")
    DEST.mkdir(parents=True, exist_ok=True)
    css = ["/* Maple Mono v7.9, OFL-1.1. Generated by scripts/build-maple-fonts.py. */"]
    translations = "".join((ROOT / f"lib/i18n/messages/{lang}.ts").read_text() for lang in ("zh-CN", "zh-TW"))
    with TemporaryDirectory() as directory, zipfile.ZipFile(archive) as source:
        (DEST / "LICENSE.txt").write_bytes(source.read("LICENSE.txt"))
        for style, weight in (("Regular", 400), ("Bold", 700)):
            name = f"MapleMonoNormalNL-NF-CN-{style}.ttf"
            original = Path(directory) / name
            original.write_bytes(source.read(name))
            with TTFont(original) as font:
                points = set(font.getBestCmap())
            latin = {p for p in points if p < 0x3000 and not 0x2E80 <= p <= 0x2FFF}
            common = {ord(c) for c in translations if 0x3000 <= ord(c) <= 0x9FFF} & points
            remaining = points - latin - common
            groups = [("latin", sorted(latin)), ("cjk-common", sorted(common))]
            # A page loads only the ranges it actually uses, including Nerd Font icons.
            for block in sorted({p // 512 for p in remaining}):
                groups.append((f"u{block * 512:05x}", sorted(p for p in remaining if p // 512 == block)))
            encoded = set()
            for label, chars in groups:
                if not chars:
                    continue
                options = subset.Options()
                options.flavor = "woff2"
                options.layout_features = ["*"]
                options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14, 16, 17]
                options.name_legacy = True
                with TTFont(original, recalcTimestamp=False) as font:
                    sub = subset.Subsetter(options=options)
                    sub.populate(unicodes=chars)
                    sub.subset(font)
                    font.flavor = "woff2"
                    filename = f"maple-mono-{style.lower()}-{label}.woff2"
                    font.save(DEST / filename)
                with TTFont(DEST / filename) as generated:
                    encoded.update(generated.getBestCmap())
                css.append(f"@font-face {{\n  font-family: '{FAMILY}';\n  font-style: normal;\n  font-weight: {weight};\n  font-display: swap;\n  src: url('/fonts/maple-mono/{filename}') format('woff2');\n  unicode-range: {unicode_ranges(chars)};\n}}")
            assert encoded == points, f"Encoded characters were lost in {style}"
            print(f"{style}: {len(points)} characters retained across {len(groups)} subsets", flush=True)
    (ROOT / "app/fonts.css").write_text("\n\n".join(css) + "\n")
    print(f"WOFF2 total: {sum(p.stat().st_size for p in DEST.glob('*.woff2')):,} bytes", flush=True)


if __name__ == "__main__":
    build(sys.argv[1])
